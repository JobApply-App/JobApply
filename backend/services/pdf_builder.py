def _resolve_template(template_id: str | None) -> Path:
    """Return the Path for the requested template; falls back to the legacy default."""
    if template_id and template_id in _TEMPLATE_MAP:
        p = _TEMPLATE_MAP[template_id]
        if p.exists():
            return p
    return TEMPLATE_PATH

# ── Contact data — sourced exclusively from the caller's own profile, never
# from the LLM ── get_profile(user_id) (user_profile.py) is the single source
# of truth, resolving to the user's actual master_profiles DB row. If a field
# is absent there, it becomes an empty string and the template placeholder is
# blanked — nothing is guessed or hardcoded here.
def _load_contact(user_id: str) -> dict:
    from backend.services.user_profile import get_profile
    p = get_profile(user_id).get("personal", {})
    return {
        "name":     p.get("name",     ""),
        "email":    p.get("email",    ""),
        "phone":    p.get("phone",    ""),
        "linkedin": p.get("linkedin", ""),
        "location": p.get("location", ""),
    }

# Contact field names — strip these from LLM output before injection
_CONTACT_KEYS = frozenset({"name", "email", "phone", "linkedin", "location"})


# ── Low-level helpers ─────────────────────────────────────────────────────────

def _e(text: str) -> str:
    """HTML-escape a plain-text string."""
    return _html.escape(str(text or ""), quote=False)


def _t(text: str, limit: int) -> str:
    """Escape and truncate to limit characters (for short display fields only).
    Never call this on experience bullets — use _e() directly there."""
    return _e(str(text or "")[:limit])


_YEAR_RE    = re.compile(r"(?:19|20)\d{2}")
_PRESENT_RE = re.compile(r"present|current|ongoing|\bnow\b", re.IGNORECASE)


def _format_year_range(raw: str) -> str:
    """Reduce any date-range string to strict 'YYYY - YYYY' (or 'YYYY').

    Source data is inconsistent ("Late 2024 - Early 2025", "2025 - Feb 2026",
    "2023–2026", "03/2019 - 08/2022"). Rather than parsing every textual
    variant, this extracts 4-digit years only and discards everything else
    (months, days, "Late"/"Early", dashes of any kind). An open-ended range
    ("... - Present") keeps the literal "Present" as the end marker instead
    of inventing an end year.
    """
    text = str(raw or "")
    years = _YEAR_RE.findall(text)
    is_open_ended = bool(_PRESENT_RE.search(text))

    if not years:
        return "Present" if is_open_ended else ""

    start = years[0]
    end   = "Present" if is_open_ended else (years[-1] if len(years) > 1 else start)

    return start if start == end else f"{start} - {end}"


def _contact_line(value: str) -> str:
    """Return a full <span class="contact-line"> element, or empty string if blank.

    This ensures absent phone/location fields produce NO DOM node — not an
    empty span that wastes vertical space in the header.
    """
    stripped = str(value or "").strip()
    if not stripped:
        return ""
    return f'<span class="contact-line">{_e(stripped)}</span>'


def _inject(template: str, data: dict) -> str:
    """Replace every {{key}} placeholder; blank out any unreplaced ones."""
    for key, value in data.items():
        template = template.replace(f"{{{{{key}}}}}", str(value) if value is not None else "")
    return re.sub(r"\{\{[^}]+\}\}", "", template)


# ── Language: headings, direction ─────────────────────────────────────────────
# A Hebrew CV used to render in the English layout: left-to-right, with
# "PROFESSIONAL SUMMARY", "EXPERIENCE" headings over Hebrew text and the
# punctuation of every Hebrew line on the wrong side. Headings now come from
# this table and the page gets lang/dir from the CV's language.

_LABELS: dict[str, dict[str, str]] = {
    "en": {
        "summary": "Professional Summary", "summary_short": "Summary",
        "experience": "Experience", "education": "Education", "skills": "Skills",
        "languages": "Languages", "military": "Military Service",
        "volunteering": "Volunteering", "relevant": "Relevant:",
    },
    "he": {
        # "תמצית" is the Israeli CV term for the summary; "תקציר מקצועי" is a
        # calque of "Professional Summary".
        "summary": "תמצית", "summary_short": "תמצית",
        "experience": "ניסיון תעסוקתי", "education": "השכלה", "skills": "כישורים",
        "languages": "שפות", "military": "שירות צבאי",
        "volunteering": "התנדבות", "relevant": "קורסים רלוונטיים:",
    },
}
_RTL_LOCALES = {"he"}

# Fixed vocabulary in the languages section comes from the profile in English.
_HE_LANGUAGE_NAMES = {
    "hebrew": "עברית", "english": "אנגלית", "arabic": "ערבית", "russian": "רוסית",
    "french": "צרפתית", "spanish": "ספרדית", "german": "גרמנית", "amharic": "אמהרית",
    "italian": "איטלקית", "portuguese": "פורטוגזית", "yiddish": "יידיש",
}
_HE_LANGUAGE_LEVELS = {
    "native": "שפת אם", "mother tongue": "שפת אם", "fluent": "רמה גבוהה מאוד",
    "full professional proficiency": "רמה גבוהה מאוד", "professional": "רמה גבוהה",
    "professional working proficiency": "רמה גבוהה", "advanced": "רמה גבוהה",
    "conversational": "רמה בינונית", "intermediate": "רמה בינונית",
    "limited working proficiency": "רמה בינונית", "basic": "בסיסית", "elementary": "בסיסית",
}

_HEBREW_CHAR = re.compile(r"[\u0590-\u05FF]")
_LATIN_CHAR  = re.compile(r"[A-Za-z]")


def detect_cv_locale(cv_data: dict) -> str:
    """
    "he" when the CV's own prose (summary and bullets) is mostly Hebrew.

    Read from the content rather than passed in, so every path that renders a
    stored CV (cached, re-render, export, design switch) gets it right without
    each caller having to know which language the CV was written in. A Hebrew
    CV keeps English product and company names, so the bar is 40 %, not half.
    """
    parts = [str(cv_data.get("summary") or "")]
    for exp in cv_data.get("experience") or []:
        if isinstance(exp, dict):
            parts.extend(str(b) for b in exp.get("bullets") or [])
    text = " ".join(parts)
    he, en = len(_HEBREW_CHAR.findall(text)), len(_LATIN_CHAR.findall(text))
    return "he" if he and he / (he + en) >= 0.4 else "en"


def _labels(locale: str) -> dict[str, str]:
    return _LABELS.get(locale, _LABELS["en"])


# ── Section HTML builders ─────────────────────────────────────────────────────

def _build_experience(entries: list[dict]) -> str:
    parts: list[str] = []
    for exp in entries[:5]:
        role    = _t(exp.get("role",    ""), 45)
        company = _t(exp.get("company", ""), 35)
        dates   = _t(_format_year_range(exp.get("dates", "")), 22)
        bullets_html = "".join(
            f"<li>{_e(str(b or ''))}</li>"
            for b in (exp.get("bullets") or [])[:6]
        )
        parts.append(
            f'<div class="exp-entry">'
            f'  <div class="entry-hdr">'
            f'    <div class="entry-meta">'
            f'      <span class="entry-role">{role}</span>'
            f'      <span class="entry-company">{company}</span>'
            f'    </div>'
            f'    <span class="entry-dates">{dates}</span>'
            f'  </div>'
            f'  <ul class="bullets">{bullets_html}</ul>'
            f'</div>'
        )
    return "\n".join(parts)


def _build_education(entries: list[dict], L: dict | None = None) -> str:
    from backend.models.cv import LIMITS

    parts: list[str] = []
    for edu in entries[:3]:
        degree      = _t(edu.get("degree",      ""), 60)
        institution = _t(edu.get("institution", ""), LIMITS["edu_inst"])
        dates       = _t(_format_year_range(edu.get("dates", "")), 20)
        honors      = _t(edu.get("honors",      ""), 60)
        coursework  = _t(edu.get("coursework",  ""), 80)

        honors_html     = f'<span class="edu-honors">{honors}</span>' if honors else ""
        coursework_html = (
            f'<span class="edu-coursework">{(L or _LABELS["en"])["relevant"]} {coursework}</span>'
            if coursework else ""
        )

        parts.append(
            f'<div class="edu-entry">'
            f'  <div class="entry-hdr">'
            f'    <div class="entry-meta">'
            f'      <span class="edu-degree">{degree}</span>'
            f'      <span class="edu-institution">{institution}</span>'
            f'    </div>'
            f'    <span class="entry-dates">{dates}</span>'
            f'  </div>'
            f'  {honors_html}{coursework_html}'
            f'</div>'
        )
    return "\n".join(parts)


# JOB-121: must stay >= tailor.py's _SKILLS_CAP (currently 20) — that's where
# skills are actually ranked by JD relevance and selected; a tighter cap here
# would silently re-truncate that careful selection down to whatever
# arbitrary items happen to survive alphabetically/positionally. The A4 page
# this renders onto has a shrink-to-fit safety net (see the <script> block in
# each cv/*.html template) rather than a hard clip, so a generous cap here
# degrades to a slightly smaller page instead of losing content.
_SKILLS_ITEMS_PER_CATEGORY_CAP = 20


def _build_skills(skills_data: dict, L: dict | None = None) -> str:
    """
    Render skills as plain inline text.  Delimiters are written directly into
    the HTML (not via CSS ::after) so they survive PDF rendering and never
    look like interactive web-UI badge components.
    """
    from backend.models.cv import LIMITS

    categories = (skills_data or {}).get("categories", [])
    if not categories:
        return ""
    cats_html = []
    for cat in categories[:4]:
        label = _t(cat.get("label", ""), LIMITS["skill_label"])
        items = [_t(s, LIMITS["skill_item"]) for s in (cat.get("items") or [])[:_SKILLS_ITEMS_PER_CATEGORY_CAP] if s]
        if not items:
            continue
        # Bullet-separated plain text — no background, no border, no badge look.
        items_text = " · ".join(items)
        cats_html.append(
            f'<div class="skill-cat">'
            f'  <span class="skill-cat-label">{label}</span>'
            f'  <span class="skill-items">{items_text}</span>'
            f'</div>'
        )
    if not cats_html:
        return ""
    return (
        f'<div class="side-sec">'
        f'  <h2 class="sec-title">{(L or _LABELS["en"])["skills"]}</h2>'
        + "".join(cats_html) +
        f'</div>'
    )


def _build_languages(languages: list[dict], L: dict | None = None, locale: str = "en") -> str:
    """
    Render each language's name and level as two separate spans — no literal
    separator between them.  Some templates lay lang-name/lang-level side by
    side with a gap, others split them to opposite ends of the row
    (justify-content: space-between); a hardcoded "— " prefix only reads
    correctly in the first layout, so it's left to each template's own CSS.
    """
    if not languages:
        return ""
    rows = []
    for lang in languages[:5]:
        raw_name, raw_level = str(lang.get("language", "") or ""), str(lang.get("level", "") or "")
        if locale == "he":
            raw_name = _HE_LANGUAGE_NAMES.get(raw_name.strip().lower(), raw_name)
            raw_level = _HE_LANGUAGE_LEVELS.get(raw_level.strip().lower(), raw_level)
        name  = _t(raw_name, 20)
        level = _t(raw_level, 35)
        if not name:
            continue
        level_html = f'<span class="lang-level">{level}</span>' if level else ""
        rows.append(
            f'<div class="lang-row">'
            f'  <span class="lang-name">{name}</span>'
            f'  {level_html}'
            f'</div>'
        )
    if not rows:
        return ""
    return (
        f'<div class="side-sec">'
        f'  <h2 class="sec-title">{(L or _LABELS["en"])["languages"]}</h2>'
        f'  {"".join(rows)}'
        f'</div>'
    )


def _build_military(mil: dict | None, L: dict | None = None) -> str:
    """
    Render the military-service block, or nothing at all.

    Reads the canonical CVDataSchema names (role_title/unit_type). A missing or
    None section produces an empty string rather than a bare heading — absent
    must mean absent, since a "Military Service" title with nothing under it is
    worse than omitting the section for a candidate who did not serve.

    key_responsibilities is optional and usually empty: it earns page space only
    for candidates whose service IS the leadership evidence (a recent graduate),
    which is why the <ul> is omitted entirely when the list is empty rather than
    rendered as an empty container that still costs vertical rhythm.
    """
    if not mil or not mil.get("role_title"):
        return ""
    role  = _t(mil.get("role_title", ""), 45)
    unit  = _t(mil.get("unit_type",  ""), 60)   # canonical unit strings run to ~41 chars
    dates = _t(_format_year_range(mil.get("dates", "")), 20)
    # unit is optional — omit the span entirely so ::before separators (used by
    # some templates) don't leave a dangling "—" when there's no unit text.
    unit_html = f'<span class="mil-unit">{unit}</span>' if unit else ""

    responsibilities = [str(r).strip() for r in (mil.get("key_responsibilities") or []) if str(r).strip()]
    resp_html = (
        f'<ul class="bullets">{"".join(f"<li>{_e(r)}</li>" for r in responsibilities[:3])}</ul>'
        if responsibilities else ""
    )

    return (
        f'<div class="side-sec">'
        f'  <h2 class="sec-title">{(L or _LABELS["en"])["military"]}</h2>'
        f'  <div class="entry-hdr">'
        f'    <div class="entry-meta">'
        f'      <span class="mil-role">{role}</span>'
        f'      {unit_html}'
        f'    </div>'
        f'    <span class="entry-dates">{dates}</span>'
        f'  </div>'
        f'  {resp_html}'
        f'</div>'
    )


def _build_volunteering(text: str, L: dict | None = None) -> str:
    if not text:
        return ""
    return (
        f'<div class="side-sec">'
        f'  <h2 class="sec-title">{(L or _LABELS["en"])["volunteering"]}</h2>'
        f'  <div class="vol-text">{_t(text, 120)}</div>'
        f'</div>'
    )


# ── Public API ────────────────────────────────────────────────────────────────

def _flatten(cv_data: dict, user_id: str, contact: dict | None = None,
             cv_locale: str | None = None) -> dict:
    """Map TailorAgent JSON output to the flat placeholder dict the template needs.

    Contact fields come exclusively from the caller's own profile (get_profile
    (user_id)).  Any contact-like keys in cv_data are silently dropped here so
    the LLM can never override them.
    """
    # Normalise first: a CV can reach the renderer straight from storage
    # (GET /cached/{job_id}, a re-render of an old tailored_cv) without having
    # passed through the tailor pipeline, and those documents may still carry
    # the pre-unification `title`/`military` keys. Converting here means the
    # builders below read canonical names only, and an old CV keeps rendering
    # exactly as it did instead of silently losing its title and service block.
    from backend.models.cv import normalize_cv
    cv_data = normalize_cv(cv_data, context="pdf_builder")

    # Strip any contact fields the LLM may have accidentally included
    clean = {k: v for k, v in cv_data.items() if k not in _CONTACT_KEYS}

    flat: dict = {}

    # ── Contact — always from the caller's own profile, never from LLM ──────
    # name, email, linkedin → plain escaped strings (always rendered inside a
    #   static <span> in the template).
    # phone, location       → full <span> element or empty string; the template
    #   injects them raw so that a missing value leaves NO DOM node at all.
    if contact is None:
        contact = _load_contact(user_id)
    flat["name"]          = _e(contact.get("name",     ""))
    flat["email"]         = _e(contact.get("email",    ""))
    flat["linkedin"]      = _e(contact.get("linkedin", ""))
    flat["phone_line"]    = _contact_line(contact.get("phone",    ""))
    flat["location_line"] = _contact_line(contact.get("location", ""))

    # ── LLM-generated content ─────────────────────────────────────────────────
    flat["title"]   = _t((clean.get("header") or {}).get("target_title", ""), 58)
    flat["summary"] = _t(clean.get("summary", ""), 400)

    # ── Language: page direction and section headings ────────────────────────
    locale = cv_locale if cv_locale in _LABELS else detect_cv_locale(clean)
    L = _labels(locale)
    flat["lang"] = locale
    flat["dir"]  = "rtl" if locale in _RTL_LOCALES else "ltr"
    for key in ("summary", "summary_short", "experience", "education"):
        flat[f"sec_{key}"] = L[key]

    flat["experience_blocks"]    = _build_experience(clean.get("experience", []))
    flat["education_blocks"]     = _build_education(clean.get("education",  []), L)
    flat["skills_section"]       = _build_skills(clean.get("skills", {}), L)
    flat["languages_section"]    = _build_languages(clean.get("languages", []), L, locale)
    flat["military_section"]     = _build_military(clean.get("military_service"), L)
    flat["volunteering_section"] = _build_volunteering(clean.get("volunteering", ""), L)

    return flat


def render_html(cv_data: dict, template_id: str | None = None, *, user_id: str,
                contact: dict | None = None, cv_locale: str | None = None) -> str:
    """Return the fully-rendered HTML string for the CV.

    user_id selects whose contact data (name/email/phone/linkedin/location)
    gets injected — defaults to "default" (the legacy single-user scaffold)
    for backward compatibility with any caller that hasn't been updated to
    pass the real caller's user_id.
    """
    template = _resolve_template(template_id).read_text(encoding="utf-8")
    flat = _flatten(cv_data, user_id, contact, cv_locale)
    html = _inject(template, flat)
    if flat.get("dir") == "rtl":
        html = html.replace("</head>", _rtl_typography() + "</head>", 1)
    return html


# ── Hebrew typography ─────────────────────────────────────────────────────────
# The templates' fonts (Inter, Source Serif, Georgia...) have no Hebrew
# letters, so Chromium fell back to FreeSans for every Hebrew word while
# English terms stayed in the template font — two typefaces in every line,
# plus italic company names that Hebrew typography does not use. RTL pages
# now set everything in Heebo (Hebrew + Latin, SIL OFL), embedded from
# backend/templates/fonts/heebo so rendering never depends on the network.

_HEEBO_DIR = Path(__file__).resolve().parent.parent / "templates" / "fonts" / "heebo"
_HEBREW_RANGE = "U+0590-05FF, U+200C-2010, U+20AA, U+25CC, U+FB1D-FB4F"
_RTL_STYLE_CACHE: dict[str, str] = {}


def _rtl_typography() -> str:
    if "style" in _RTL_STYLE_CACHE:
        return _RTL_STYLE_CACHE["style"]
    import base64

    faces = []
    for weight in (400, 500, 700):
        for subset, rng in (("latin", None), ("hebrew", _HEBREW_RANGE)):
            path = _HEEBO_DIR / f"heebo-{subset}-{weight}-normal.woff2"
            if not path.exists():
                logger.error("[pdf_builder] Hebrew font missing: %s — falling back to system fonts", path)
                continue
            data = base64.b64encode(path.read_bytes()).decode()
            unicode_range = f" unicode-range: {rng};" if rng else ""
            faces.append(
                f"@font-face {{ font-family: 'Heebo'; font-style: normal; font-weight: {weight};"
                f" font-display: block; src: url(data:font/woff2;base64,{data}) format('woff2');{unicode_range} }}"
            )
    # 600 is used by several templates; map it to the 700 face rather than
    # letting Chromium synthesise a fake bold.
    style = (
        "<style>\n" + "\n".join(faces) + "\n"
        "html[dir=\"rtl\"] body, html[dir=\"rtl\"] body * {"
        " font-family: 'Heebo', Arial, sans-serif !important; font-style: normal !important; }\n"
        "html[dir=\"rtl\"] body { line-height: 1.45; }\n"
        "</style>\n"
    )
    _RTL_STYLE_CACHE["style"] = style
    return style


async def build_pdf(cv_data: dict, output_path: str | Path | None = None,
                    template_id: str | None = None, *, user_id: str,
                    cv_locale: str | None = None) -> bytes:
    """
    Render cv_data to a single-page A4 PDF using Playwright headless Chromium.

    Returns raw PDF bytes. If output_path is provided, also writes the file.
    """
    from playwright.async_api import async_playwright

    from backend.services.chromium_slot import chromium_slot

    contact  = _load_contact(user_id)
    html_str = render_html(cv_data, template_id=template_id, user_id=user_id, contact=contact,
                           cv_locale=cv_locale)

    async with chromium_slot(), async_playwright() as pw:
        try:
            browser = await pw.chromium.launch()
        except Exception as exc:
            # Matched on the message rather than the exception class:
            # playwright._impl._errors.Error is a private path, and the same
            # class covers ordinary launch failures too. The wording below is
            # what Playwright prints when the binary is absent.
            msg = str(exc).lower()
            if "executable doesn't exist" in msg or "playwright install" in msg:
                raise PdfEngineUnavailable(
                    "Chromium is not installed in this environment — PDF rendering "
                    "is unavailable. Deploy via backend/Dockerfile (which runs "
                    "`playwright install --with-deps chromium`), or run that command "
                    "with system dependencies available."
                ) from exc
            raise
        page    = await browser.new_page()
        await page.set_content(html_str, wait_until="networkidle")
        pdf_bytes = await page.pdf(
            format="A4",
            print_background=True,
            prefer_css_page_size=True,
            # tagged=True writes real PDF structure tags (headings, lists,
            # reading order) derived from the HTML's own semantic markup —
            # required for SI 5568 Part 2 (accessible digital documents) and
            # for any screen reader to make sense of the exported CV at all.
            # outline=True builds the PDF's bookmark tree from the same <h1>-
            # <h6> hierarchy. Both need Playwright >= 1.42 (pinned: 1.49.1)
            # and both depend on the templates using real heading tags rather
            # than styled <div>/<span> — see templates/cv/*.html.
            tagged=True,
            outline=True,
        )
        await browser.close()

    ats_text_issues(pdf_bytes, contact)

    if output_path is not None:
        Path(output_path).write_bytes(pdf_bytes)

    return pdf_bytes


# ── ATS text-layer check ──────────────────────────────────────────────────────


_NO_SPACE = re.compile(r"\s+")
_PHONE_PUNCT = re.compile(r"[\s\-().+\u200e\u200f]")


def _pdf_text_pages(pdf_bytes: bytes) -> list[str]:
    import fitz  # pymupdf
    with fitz.open(stream=pdf_bytes, filetype="pdf") as doc:
        return [page.get_text() for page in doc]


def ats_text_issues(pdf_bytes: bytes, contact: dict) -> list[str]:
    """
    Read the rendered PDF the way an ATS parser does — its text layer, not the
    picture — and return what a parser would miss: contact details that don't
    extract as literal text, or a CV that spilled past one page.

    Advisory: it logs and returns, never blocks the download. Logged without
    the values themselves (they are the user's personal details).
    """
    try:
        pages = _pdf_text_pages(pdf_bytes)
    except Exception as exc:
        logger.warning("[pdf_builder] ATS check could not read the PDF: %s", exc)
        return ["unreadable"]

    text = "\n".join(pages)
    flat = _NO_SPACE.sub("", text).lower()
    issues: list[str] = []
    if not flat:
        issues.append("no_text_layer")
    else:
        email = _NO_SPACE.sub("", contact.get("email") or "").lower()
        if email and email not in flat:
            issues.append("email")
        # Last 9 digits: the same number is written +972-54… on the profile and
        # 054… on a CV, so the country/trunk prefix must not decide the match.
        phone = re.sub(r"\D", "", contact.get("phone") or "")[-9:]
        if phone and phone not in _PHONE_PUNCT.sub("", text):
            issues.append("phone")
        # Word by word: a Hebrew name extracts with its words in visual order
        # ("לוי דנה" for "דנה לוי"), which a parser still reads as the name.
        words = (contact.get("name") or "").lower().split()
        if words and not all(w in flat for w in words):
            issues.append("name")
    if len(pages) > 1:
        issues.append(f"pages={len(pages)}")

    if issues:
        logger.warning("[pdf_builder] ATS text-layer check: %s", ", ".join(issues))
    return issues
